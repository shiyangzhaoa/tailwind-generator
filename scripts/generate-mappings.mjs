import { readFileSync, writeFileSync } from 'node:fs';
import { isDeepStrictEqual } from 'node:util';
import { decodeMappings } from '../src/core/mapping-codec.mts';
const root = new URL('../', import.meta.url);
const source = JSON.parse(
  readFileSync(new URL('data/tailwind-4.1.json', root), 'utf8'),
);
// Documentation patterns such as <value> are not executable mappings.
const entries = source.entries.filter(
  (entry) => !/[<>]/.test(JSON.stringify(entry)),
);
const seen = new Set();
for (const entry of entries) {
  if (
    !entry.classes ||
    !Object.keys(entry.declarations).length ||
    Object.values(entry.declarations).some((value) => typeof value !== 'string')
  ) {
    throw new Error('Invalid mapping entry');
  }
  const key = JSON.stringify(Object.entries(entry.declarations).sort());
  if (seen.has(key)) throw new Error(`Duplicate declaration mapping: ${key}`);
  seen.add(key);
}

// A single declaration whose value embeds the end of its class name, such as
// `bg-red-500` → `background-color: var(--color-red-500)`, is stored as a
// template plus a shared name list. Only templates with this many members are
// worth it; everything else stays literal.
const minimumTemplateSize = 4;
function shape(entry) {
  const declarations = Object.entries(entry.declarations);
  if (declarations.length !== 1) return undefined;
  const [[property, value]] = declarations;
  const parts = entry.classes.split('-');
  for (let i = 1; i < parts.length; i++) {
    const name = parts.slice(i).join('-');
    const at = value.indexOf(name);
    if (at < 0 || value.indexOf(name, at + 1) >= 0) continue;
    const prefix = `${parts.slice(0, i).join('-')}-`;
    return {
      key: JSON.stringify([
        property,
        prefix,
        value.slice(0, at),
        value.slice(at + name.length),
      ]),
      name,
    };
  }
  return undefined;
}
const groups = new Map();
for (const entry of entries) {
  const found = shape(entry);
  if (!found) continue;
  const group = groups.get(found.key) ?? [];
  group.push({ entry, name: found.name });
  groups.set(found.key, group);
}
const templated = new Set();
const names = [];
const nameIndex = new Map();
const templates = [];
for (const [key, members] of [...groups].sort(([a], [b]) => (a < b ? -1 : 1))) {
  if (members.length < minimumTemplateSize) continue;
  const list = members.map(({ name }) => name).sort();
  const listKey = JSON.stringify(list);
  if (!nameIndex.has(listKey)) {
    nameIndex.set(listKey, names.length);
    names.push(list);
  }
  templates.push([...JSON.parse(key), nameIndex.get(listKey)]);
  for (const { entry } of members) templated.add(entry);
}
// Literals keep source order: it decides ties between combined mappings.
const literals = entries
  .filter((entry) => !templated.has(entry))
  .map((entry) => [Object.entries(entry.declarations), entry.classes]);
const data = { templates, names, literals };

const canonical = (list) =>
  list
    .map(({ declarations, classes }) =>
      JSON.stringify([Object.entries(declarations).sort(), classes]),
    )
    .sort();
const decoded = decodeMappings(data);
if (!isDeepStrictEqual(canonical(decoded), canonical(entries)))
  throw new Error('Encoded mappings do not decode to the source entries');
if (
  !isDeepStrictEqual(
    decoded.slice(0, literals.length),
    entries.filter((entry) => !templated.has(entry)),
  )
)
  throw new Error('Literal mappings lost their source order');

const output = `// Generated by scripts/generate-mappings.mjs. Do not edit.\n// Tailwind ${source.tailwindVersion}; source: data/tailwind-4.1.json\nimport { decodeMappings, type MappingData } from '../core/mapping-codec.mjs';\n\nconst data: MappingData = JSON.parse(${JSON.stringify(JSON.stringify(data))});\n\nexport const mappings = decodeMappings(data);\n`;
const destination = new URL('src/generated/mappings.mts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(destination, 'utf8') !== output)
    throw new Error('Mappings are stale; run npm run generate:mappings');
} else {
  writeFileSync(destination, output);
}
const tokens = `// Generated by scripts/generate-mappings.mjs. Do not edit.\nexport const designTokens: Record<string, string> = ${JSON.stringify(source.tokens, null, 2)};\nexport const designTokenVars: Record<string, string> = Object.fromEntries(Object.entries(designTokens).map(([key, value]) => [value, \`var(\${key})\`]));\n`;
const tokenDestination = new URL('src/tokens.mts', root);
if (process.argv.includes('--check')) {
  if (readFileSync(tokenDestination, 'utf8') !== tokens)
    throw new Error('Tokens are stale; run npm run generate:mappings');
} else writeFileSync(tokenDestination, tokens);
console.log(
  `Verified ${entries.length} concrete mappings for Tailwind ${source.tailwindVersion}`,
);
